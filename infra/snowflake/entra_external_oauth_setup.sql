-- ============================================================================
-- Snowflake Enterprise Setup for Keyless Entra ID (Managed Identity & DevBox)
-- + LangGraph Hybrid Table Checkpointer + Least-Privilege dbt Role
-- ============================================================================

USE ROLE ACCOUNTADMIN;

-- 1. Network Policy: Whitelist Azure Container Apps Egress / NAT Gateway IP
--    and Corporate DevBox Egress CIDRs (or enforce Azure Private Link).
CREATE OR REPLACE NETWORK RULE CORP_AZURE_AND_DEVBOX_RULE
  MODE = INGRESS
  TYPE = IPV4
  VALUE_LIST = (
    '20.105.44.12/32',   -- Corporate DevBox Egress NAT IP
    '198.51.100.0/24'    -- Corporate VPN / ACA NAT Gateway Subnet
  )
  COMMENT = 'Whitelisted Azure Container Apps egress and corporate DevBox CIDRs';

CREATE OR REPLACE NETWORK POLICY CORP_LANGGRAPH_NETWORK_POLICY
  ALLOWED_NETWORK_RULE_LIST = ('CORP_AZURE_AND_DEVBOX_RULE');

-- 2. Keyless Entra ID External OAuth Security Integration
--    Allows ACA User-Assigned Managed Identity AND DevBox engineers (`az login`)
--    to authenticate to Snowflake using Entra OAuth2 tokens (`authenticator="oauth"`).
CREATE OR REPLACE SECURITY INTEGRATION ENTRA_ID_LANGGRAPH_OAUTH
  TYPE = EXTERNAL_OAUTH
  ENABLED = TRUE
  EXTERNAL_OAUTH_TYPE = AZURE
  EXTERNAL_OAUTH_ISSUER = 'https://sts.windows.net/<YOUR_ENTRA_TENANT_ID>/'
  EXTERNAL_OAUTH_JWS_KEYS_URL = 'https://login.microsoftonline.com/<YOUR_ENTRA_TENANT_ID>/discovery/v2.0/keys'
  EXTERNAL_OAUTH_AUDIENCE_LIST = ('api://<SNOWFLAKE_ENTRA_RESOURCE_APP_ID>')
  -- For Managed Identities (Service Principals), map the Entra `oid` or `sub` claim to `SNOWFLAKE_USER.LOGIN_NAME`
  EXTERNAL_OAUTH_TOKEN_USER_MAPPING_CLAIM = ('oid', 'upn', 'unique_name')
  EXTERNAL_OAUTH_SNOWFLAKE_USER_MAPPING_ATTRIBUTE = 'LOGIN_NAME'
  EXTERNAL_OAUTH_ANY_ROLE_MODE = 'ENABLE';

-- 3. Create Least-Privilege Role & Service User for the ACA Managed Identity
CREATE ROLE IF NOT EXISTS RL_LANGGRAPH_AGENT;
CREATE WAREHOUSE IF NOT EXISTS WH_LANGGRAPH_XS
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON WAREHOUSE WH_LANGGRAPH_XS TO ROLE RL_LANGGRAPH_AGENT;

-- Create the Snowflake user mapped to the ACA User-Assigned Managed Identity Principal ID (OID)
CREATE USER IF NOT EXISTS SVC_ACA_LANGGRAPH
  LOGIN_NAME = '<ACA_UAMI_PRINCIPAL_OID>'
  DISPLAY_NAME = 'ACA LangGraph Managed Identity (id-lgorchestrator)'
  DEFAULT_ROLE = RL_LANGGRAPH_AGENT
  DEFAULT_WAREHOUSE = WH_LANGGRAPH_XS
  TYPE = SERVICE;

GRANT ROLE RL_LANGGRAPH_AGENT TO USER SVC_ACA_LANGGRAPH;

-- 4. Create State & Audit Database / Schema for LangGraph Checkpoints & HITL Audit Trail
CREATE DATABASE IF NOT EXISTS AGENT_STATE_DB;
CREATE SCHEMA IF NOT EXISTS AGENT_STATE_DB.LANGGRAPH;

GRANT USAGE ON DATABASE AGENT_STATE_DB TO ROLE RL_LANGGRAPH_AGENT;
GRANT USAGE, CREATE TABLE ON SCHEMA AGENT_STATE_DB.LANGGRAPH TO ROLE RL_LANGGRAPH_AGENT;

-- Hybrid Table (or Standard Table) for fast transactional LangGraph thread checkpoints
CREATE TABLE IF NOT EXISTS AGENT_STATE_DB.LANGGRAPH.THREAD_CHECKPOINTS (
  THREAD_ID VARCHAR(255) NOT NULL,
  RUN_ID VARCHAR(128) NOT NULL,
  EVENT_KEY VARCHAR(128) NOT NULL,
  STATUS VARCHAR(64) NOT NULL,
  ACTOR_UPN VARCHAR(255),
  STATE_JSON VARIANT NOT NULL,
  UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_THREAD_CHECKPOINTS PRIMARY KEY (THREAD_ID, RUN_ID)
);

-- Tamper-Evident HITL Adaptive Card Approval Audit Log (Teams & Outlook)
CREATE TABLE IF NOT EXISTS AGENT_STATE_DB.LANGGRAPH.HITL_AUDIT_LOG (
  AUDIT_ID VARCHAR(128) NOT NULL PRIMARY KEY,
  THREAD_ID VARCHAR(255) NOT NULL,
  RUN_ID VARCHAR(128) NOT NULL,
  CHANNEL_ORIGIN VARCHAR(64) NOT NULL, -- 'ms_teams' | 'outlook' | 'devbox'
  REQUESTED_BY_UPN VARCHAR(255) NOT NULL,
  APPROVED_BY_UPN VARCHAR(255) NOT NULL,
  DECISION VARCHAR(32) NOT NULL,       -- 'approve' | 'reject'
  ACTION_DIGEST VARCHAR(64) NOT NULL,
  DBT_MODEL_NAME VARCHAR(255),
  ADO_PR_ID NUMBER,
  CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA AGENT_STATE_DB.LANGGRAPH TO ROLE RL_LANGGRAPH_AGENT;

-- 5. Grant Read-Only Metadata & EXPLAIN Access on Analytics / dbt Prod Database
--    (Agent never mutates PROD tables directly; mutations happen only via Azure DevOps PR + dbt CI!)
GRANT USAGE ON DATABASE ANALYTICS_PROD TO ROLE RL_LANGGRAPH_AGENT;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS_PROD TO ROLE RL_LANGGRAPH_AGENT;
GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS_PROD TO ROLE RL_LANGGRAPH_AGENT;
GRANT SELECT ON ALL VIEWS IN DATABASE ANALYTICS_PROD TO ROLE RL_LANGGRAPH_AGENT;
